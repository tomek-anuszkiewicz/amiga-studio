"""Render existing verification timings without executing or selecting work."""
from collections import Counter
from datetime import datetime, timezone
from hashlib import sha256
from pathlib import Path
import time

from repository import git


REPORT_NAME = "test-runtime-report.md"


def measurement(phase, group, title, status, seconds=None, previous_seconds=None, commands=()):
    return {"phase": phase, "group": group, "title": title, "status": status,
            "seconds": seconds, "previous_seconds": previous_seconds, "commands": commands}


def command_scope(root, command):
    """Describe actual selectors without exposing host paths or inline code."""
    words = [Path(command[0]).name]
    for word in command[1:]:
        if word in {"-c", "-Command"}:
            words.extend((word, "<inline command>"))
            break
        path = Path(word)
        if path.is_absolute():
            word = path.relative_to(root).as_posix() if path.is_relative_to(root) else "<external path>"
        words.append(word)
    return " ".join(words)


def render(root, profile, revision, rows, wall_seconds):
    lines = ["# Test runtime report", "", "Generated by repository verification; do not edit.", "",
             f"- Profile: `{profile}`; HEAD: `{revision}`.",
             "  Timings describe the working candidate, which may contain pending changes beyond HEAD.",
             f"- Recorded at: {datetime.now(timezone.utc).isoformat(timespec='seconds')}.",
             f"- Invocation wall time before report generation: {wall_seconds:.3f} s.",
             "- Command times include child startup and bookkeeping. Cargo test commands include",
             "  compilation/reuse and test execution; those shares are not separately measured.",
             "- Reused times describe the retained execution, not time spent running tests now.",
             "  Missing or skipped work provides no current test evidence. Internal evidence owns the verdict.",
             "- Coverage preparation, export and summary appear separately when selected.",
             "  Generation and file-writing costs are measured separately in the console and batch record.", "",
             "| Phase | Group / command | Scope | Status | Current command wall (s) | Retained execution (s) |",
             "| --- | --- | --- | --- | ---: | ---: |"]
    for row in rows:
        title = row["title"].replace("|", "\\|").replace("\n", " ")
        group = row["group"].replace("|", "\\|")
        label = title if title == group else f"{group}: {title}"
        current = "—" if row["seconds"] is None else f"{row['seconds']:.3f}"
        retained = "—" if row["previous_seconds"] is None else f"{row['previous_seconds']:.3f}"
        scope = "; ".join(command_scope(root, command) for command in row["commands"])
        scope = scope.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace(">", "&gt;")
        lines.append(f"| {row['phase']} | {label} | {scope} | {row['status']} | {current} | {retained} |")
    lines += ["", "Each command duration is wall time. Concurrent commands overlap, so their durations",
              "must not be added to obtain invocation wall time or test-case CPU time.",
              "This report is output only; it is not a verification input or a replacement for logs.", ""]
    return "\n".join(lines)


def publish(root, output_root, directory, profile, rows, wall_seconds):
    started = time.perf_counter()
    revision = git(root, "rev-parse", "HEAD").decode().strip()
    content = render(root, profile, revision, rows, wall_seconds).encode("utf-8")
    digest = sha256(content).hexdigest()
    generated = time.perf_counter() - started
    started = time.perf_counter()
    path = directory / REPORT_NAME
    directory.mkdir(parents=True, exist_ok=True)
    with path.open("xb") as report:
        report.write(content)
    written = time.perf_counter() - started
    counts = Counter(row["status"] for row in rows)
    print("[TIMING] " + ", ".join(f"{count} {status}" for status, count in sorted(counts.items())))
    for phase in dict.fromkeys(row["phase"] for row in rows):
        seconds = sum(row["seconds"] or 0 for row in rows if row["phase"] == phase)
        print(f"[TIMING] {phase}: {seconds:.3f}s current command wall time")
    print(f"[TIMING] Report generation: {generated:.6f}s; file writing: {written:.6f}s; {path}")
    print(f"[TIMING] Report SHA-256: {digest}")
    return {"generation_seconds": generated, "write_seconds": written, "rows": rows,
            "wall_seconds_before_report": wall_seconds,
            "path": path.relative_to(output_root).as_posix(), "sha256": digest}
