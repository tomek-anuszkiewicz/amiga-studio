"""Visibility editing through the real HTTP queue and browser review UI."""
from http.server import ThreadingHTTPServer
from pathlib import Path
import sys
import tempfile
import threading
import unittest

from PIL import Image
from playwright.sync_api import sync_playwright

REVIEW = Path(__file__).resolve().parents[4] / 'tools/bootstrap/book-to-markdown'
sys.path.insert(0, str(REVIEW))
from review.model import load_input, write_json
from review.service import Handler, ReviewState


class VisibilityReviewTest(unittest.TestCase):
    def test_hide_preview_accept_and_unhide(self):
        book = {'toc': {'depth': 2}, 'chapters': [{'id': 'chapter', 'title': 'Example',
            'markdown_file': 'example.md', 'elements': [
                {'id': 'heading', 'type': 'heading', 'heading_level': 2,
                 'md_text': '## Example heading', 'pdf_regions': [{'page': 1, 'bbox': [20, 20, 180, 60]}], 'role': None},
                {'id': 'prose', 'type': 'prose', 'md_text': 'Ordinary visible paragraph.', 'pdf_regions': [{'page': 2, 'bbox': [20, 20, 180, 60]}], 'role': None}]}]}
        with tempfile.TemporaryDirectory() as temporary:
            root = Path(temporary)
            (root / 'pdf/pages').mkdir(parents=True)
            for number in (1, 2, 3):
                Image.new('RGB', (200, 300), 'white').save(root / f'pdf/pages/page_{number:04d}.png')
            write_json(root / 'working/book.json', book)
            state = ReviewState(root)
            server = ThreadingHTTPServer(('127.0.0.1', 0), Handler)
            server.daemon_threads = True
            server.state = state
            worker = threading.Thread(target=state.render_loop)
            http = threading.Thread(target=server.serve_forever)
            worker.start()
            http.start()
            try:
                with sync_playwright() as playwright:
                    browser = playwright.chromium.launch(channel='msedge')
                    page = browser.new_page(viewport={'width': 1600, 'height': 950})
                    errors = []
                    page.on('pageerror', lambda error: errors.append(str(error)))
                    page.goto(f'http://127.0.0.1:{server.server_port}/')
                    page.wait_for_function('state?.can_accept && !loading')
                    self.assertFalse(page.locator("#discard").is_enabled())
                    for selector in ('#pdf [data-id="heading"]', '#accepted [data-element="heading"]', '#working [data-element="heading"]'):
                        page.locator(selector).click(button='right')
                        self.assertEqual(page.locator('#menu-current-role').inner_text(), 'Role: None')
                        page.locator('#menu-role').click()
                        page.locator('#role-menu').get_by_role('menuitemradio', name='note', exact=True).click()
                        page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].role === "note"')
                        page.locator(selector).click(button='right')
                        self.assertEqual(page.locator('#menu-current-role').inner_text(), 'Role: None / note')
                        page.locator('#menu-role').click()
                        page.locator('#role-menu button').filter(has_text='None').click()
                        page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].role === null')
                    page.keyboard.press('Escape')
                    heading = page.locator('#working [data-element="heading"]')
                    heading.click()
                    self.assertEqual(page.evaluate('selected'), 'heading')
                    heading.click()
                    self.assertIsNone(page.evaluate('selected'))
                    self.assertEqual(page.locator('#pdf .selected').count(), 0)
                    self.assertTrue(page.locator('#element-actions').is_disabled())
                    heading.click()
                    page.keyboard.press('Escape')
                    self.assertIsNone(page.evaluate('selected'))
                    page.screenshot(path='.agent/tmp/book-review-escape.png')
                    self.assertFalse(heading.evaluate('(n)=>n.matches(":focus")'))
                    self.assertEqual(heading.evaluate('(n)=>getComputedStyle(n).outlineStyle'), 'none')
                    heading.click()
                    page.locator('#pdf .page[data-page="1"]').click(position={'x': 5, 'y': 5})
                    self.assertIsNone(page.evaluate('selected'))
                    heading.click()
                    page.locator('#working').click(position={'x': 5, 'y': 800})
                    self.assertIsNone(page.evaluate('selected'))
                    self.assertFalse(page.locator('#element-menu').is_visible())
                    heading.click(button='right')
                    self.assertEqual(page.locator('#menu-discard').inner_text(), 'Discard')
                    self.assertFalse(page.locator('#menu-discard').is_enabled())
                    page.keyboard.press('Escape')
                    page.locator('#working [data-element="prose"]').click(button='right')
                    page.locator('#menu-visibility').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[1].visible === false')
                    heading.click(button='right')
                    self.assertEqual(page.locator('#menu-heading').inner_text(), 'Heading H2 ▸')
                    page.locator('#menu-heading').click()
                    current = page.locator('#heading-menu button[data-level="2"]')
                    self.assertEqual(current.get_attribute('aria-checked'), 'true')
                    self.assertEqual(current.evaluate('(n)=>getComputedStyle(n).fontWeight'), '700')
                    self.assertNotEqual(current.evaluate('(n)=>getComputedStyle(n).backgroundColor'),
                                        page.locator('#heading-menu button[data-level="3"]').evaluate('(n)=>getComputedStyle(n).backgroundColor'))
                    page.locator('#heading-menu button[data-level="4"]').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].heading_level === 4')
                    heading.click(button='right')
                    self.assertEqual(page.locator('#menu-heading').inner_text(), 'Heading H4 ▸')
                    page.locator('#menu-heading').click()
                    self.assertEqual(page.locator('#heading-menu button[data-level="4"]').get_attribute('aria-checked'), 'true')
                    self.assertTrue(page.locator('#menu-discard').is_enabled())
                    page.locator('#menu-discard').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].heading_level === 2')
                    self.assertFalse(load_input(root / 'working')[0]['chapters'][0]['elements'][1]['visible'])
                    self.assertEqual([change['id'] for change in state.status()['changes']], ['prose'])
                    page.locator('#show-hidden').check()
                    page.locator('#pdf [data-id="prose"]').click(button='right')
                    page.locator('#menu-discard').click()
                    page.wait_for_function('!loading && state.can_accept && state.changes.length === 0')
                    page.locator('#show-hidden').uncheck()
                    page.locator('#accepted [data-element="heading"]').click(button='right')
                    self.assertFalse(page.locator('#menu-discard').is_enabled())
                    self.assertTrue(page.locator('#menu-visibility').is_enabled())
                    self.assertTrue(page.locator('#menu-bold').is_enabled())
                    self.assertEqual(page.locator('#menu-fix-callouts').count(), 0)
                    self.assertTrue(page.locator('#menu-move-down').is_enabled())
                    accepted_before = (root / 'accepted/book.json').read_bytes()
                    page.locator('#menu-bold').click()
                    page.wait_for_function('!loading && state.can_accept && state.changes.length > 0')
                    self.assertEqual((root / 'accepted/book.json').read_bytes(), accepted_before)
                    page.locator('#accepted [data-element="heading"]').click(button='right')
                    page.locator('#menu-discard').click()
                    page.wait_for_function('!loading && state.can_accept && state.changes.length === 0')
                    page.keyboard.press('Escape')
                    heading.click()
                    self.assertFalse(page.locator('#heading-menu').is_visible())
                    page.locator('#element-actions').click()
                    self.assertEqual(page.locator('#menu-visibility').inner_text(), 'Hide Element')
                    self.assertTrue(page.locator('#menu-heading').is_visible())
                    page.locator('#menu-heading').click()
                    self.assertTrue(page.locator('#heading-menu').is_visible())
                    self.assertEqual(page.locator('#heading-menu button').all_text_contents(), ['H1', 'H2', 'H3', 'H4', 'H5', 'H6'])
                    page.keyboard.press('Escape')
                    stale_revision = state.status()['authored_revision']
                    heading.click(button='right')
                    page.locator('#menu-visibility').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].visible === false')
                    self.assertFalse(heading.is_visible())
                    pdf_heading = page.locator('#pdf [data-id="heading"]')
                    self.assertEqual(pdf_heading.count(), 1)
                    self.assertFalse(pdf_heading.is_visible())
                    pdf_page = page.locator('#pdf .page[data-page="1"]')
                    self.assertFalse(pdf_page.is_visible())
                    self.assertTrue(page.locator('#pdf .page[data-page="2"]').is_visible())
                    self.assertFalse(page.locator('#pdf .page[data-page="3"]').is_visible())
                    self.assertTrue(page.locator('#accepted [data-element="heading"]').is_visible())
                    hidden = load_input(root / 'working')[0]
                    self.assertFalse(hidden['chapters'][0]['elements'][0]['visible'])
                    requests = []
                    page.on('request', lambda request: requests.append(request.url))
                    page.locator('#show-hidden').check()
                    self.assertTrue(heading.is_visible())
                    self.assertTrue(pdf_heading.is_visible())
                    self.assertTrue(pdf_page.is_visible())
                    self.assertTrue(page.locator('#pdf .page[data-page="3"]').is_visible())
                    self.assertIn('hidden-element', heading.get_attribute('class'))
                    self.assertIn('radial-gradient', heading.evaluate('(n)=>getComputedStyle(n,"::after").backgroundImage'))
                    self.assertFalse(any('/api/' in url for url in requests))
                    self.assertEqual(load_input(root / 'working')[0], hidden)
                    heading.hover()
                    self.assertEqual(page.locator('#element-hint, [role="tooltip"]').count(), 0)
                    self.assertNotIn('Example heading', page.locator('#working [data-element="generated-toc"]').inner_text())
                    pdf_heading.click(button='right')
                    self.assertEqual(page.locator('#menu-visibility').inner_text(), 'Unhide Element')
                    self.assertTrue(page.locator('#menu-visibility').is_enabled())
                    page.keyboard.press('Escape')
                    heading.focus()
                    page.keyboard.press('Shift+F10')
                    self.assertEqual(page.locator('#menu-visibility').inner_text(), 'Unhide Element')
                    page.keyboard.press('Escape')
                    self.assertFalse(page.locator('#element-menu').is_visible())
                    page.locator('#accepted [data-element="heading"]').click(button='right')
                    self.assertTrue(page.locator('#menu-visibility').is_enabled())
                    page.keyboard.press('Escape')
                    response = page.request.post(f'http://127.0.0.1:{server.server_port}/api/visibility', data={
                        'id': 'heading', 'visible': True, 'expected_revision': stale_revision})
                    self.assertEqual(response.status, 409)
                    page.locator('#accept').click()
                    page.wait_for_function('!loading && state.accepted.chapters[0].elements[0].visible === false')
                    self.assertNotIn('Example heading', (root / 'accepted/example.md').read_text(encoding='utf-8'))
                    self.assertNotIn('Example heading', (root / 'accepted/table-of-contents.md').read_text(encoding='utf-8'))
                    heading.click(button='right')
                    Path('.agent/tmp').mkdir(parents=True, exist_ok=True)
                    page.screenshot(path='.agent/tmp/book-review-hidden-menu.png')
                    page.locator('#menu-visibility').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[0].visible === true')
                    self.assertNotIn('hidden-element', heading.get_attribute('class') or '')
                    self.assertIn('Example heading', page.locator('#working [data-element="generated-toc"]').inner_text())
                    page.locator('#show-hidden').uncheck()
                    self.assertTrue(heading.is_visible())
                    self.assertTrue(pdf_page.is_visible())
                    self.assertFalse(page.locator('#accepted [data-element="heading"]').is_visible())
                    page.locator('#toc-depth').select_option('3')
                    page.wait_for_function('!loading && state.can_discard && state.working.toc.depth === 3')
                    response = page.request.post(f'http://127.0.0.1:{server.server_port}/api/discard', data={
                        'expected_revision': 'stale', 'accepted_revision': state.accepted['revision']})
                    self.assertEqual(response.status, 409)
                    page.locator('#discard').click()
                    page.wait_for_function('!loading && !state.can_discard && state.changes.length === 0 && state.working.toc.depth === 2')
                    self.assertFalse(heading.is_visible())
                    self.assertFalse(pdf_page.is_visible())
                    self.assertFalse(page.locator('#discard').is_enabled())
                    self.assertEqual(load_input(root / 'working'), load_input(root / 'accepted'))
                    for filename in ('example.md', 'table-of-contents.md'):
                        self.assertEqual((root / 'working' / filename).read_bytes(),
                                         (root / 'accepted' / filename).read_bytes())
                    accepted_before = (root / 'accepted/book.json').read_bytes()
                    accepted_dom = page.locator('#accepted .chapter-content').first.element_handle()
                    pdf_dom = page.locator('#pdf .page[data-page="2"]').element_handle()
                    prose = page.locator('#working [data-element="prose"]')
                    prose.click(button='right')
                    page.locator('#menu-bold').click()
                    self.assertFalse(page.locator('#markdown-dialog').is_visible())
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[1].resolved_md_text.startsWith("**")')
                    self.assertEqual(prose.locator('strong').inner_text(), 'Ordinary visible paragraph.')
                    self.assertEqual(load_input(root / 'working')[0]['chapters'][0]['elements'][1]['resolved_md_text'], '**Ordinary visible paragraph.**')
                    self.assertTrue(accepted_dom.evaluate('(n)=>n.isConnected'))
                    self.assertTrue(pdf_dom.evaluate('(n)=>n.isConnected'))
                    self.assertEqual(page.evaluate('nodes.pdf.find(e=>e.id==="prose").source.element.resolved_md_text'), '**Ordinary visible paragraph.**')
                    prose.click(button='right')
                    page.locator('#menu-remove-bold').click()
                    self.assertFalse(page.locator('#markdown-dialog').is_visible())
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[1].resolved_md_text === "Ordinary visible paragraph."')
                    prose.click(button='right')
                    page.locator('#menu-bold').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[1].resolved_md_text.startsWith("**")')
                    prose.click(button='right')
                    page.locator('#menu-markdown').click()
                    page.locator('#remove-bold').click()
                    self.assertEqual(page.locator('#markdown-text').input_value(), 'Ordinary visible paragraph.')
                    page.locator('#cancel-markdown').click()
                    self.assertTrue(load_input(root / 'working')[0]['chapters'][0]['elements'][1]['resolved_md_text'].startswith('**'))
                    prose.click(button='right')
                    page.locator('#menu-markdown').click()
                    page.locator('#markdown-text').fill('First {manual} paragraph.\n\nSecond paragraph.')
                    page.locator('#save-markdown').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements[1].resolved_md_text.startsWith("First")')
                    prose.click(button='right')
                    page.locator('#menu-split').click()
                    self.assertFalse(page.locator('#save-markdown').is_enabled())
                    page.locator('#markdown-text').evaluate('(n)=>n.setSelectionRange(0,n.value.indexOf("Second"))')
                    page.locator('#split-at-cursor').click()
                    self.assertEqual(page.locator('#markdown-second').input_value(), 'Second paragraph.')
                    Path('.agent/tmp').mkdir(parents=True, exist_ok=True)
                    page.screenshot(path='.agent/tmp/book-review-split.png')
                    page.locator('#save-markdown').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements.length === 3')
                    split_elements = load_input(root / 'working')[0]['chapters'][0]['elements'][1:]
                    self.assertEqual([e['resolved_md_text'] for e in split_elements], ['First {manual} paragraph.\n\n', 'Second paragraph.'])
                    self.assertEqual(split_elements[0]['pdf_regions'], split_elements[1]['pdf_regions'])
                    self.assertEqual(page.locator('#working [data-element]').count(), 4)
                    self.assertEqual((root / 'accepted/book.json').read_bytes(), accepted_before)
                    prose.click(button='right')
                    page.locator('#menu-merge').click()
                    self.assertEqual(page.locator('#markdown-text').input_value(), 'First {manual} paragraph.\n\n\nSecond paragraph.')
                    page.locator('#cancel-markdown').click()
                    self.assertEqual(len(load_input(root / 'working')[0]['chapters'][0]['elements']), 3)
                    prose.click(button='right')
                    page.locator('#menu-merge').click()
                    page.locator('#markdown-text').fill('First {manual} paragraph.\nSecond paragraph.')
                    page.screenshot(path='.agent/tmp/book-review-merge.png')
                    page.locator('#save-markdown').click()
                    page.wait_for_function('!loading && state.can_accept && state.working.chapters[0].elements.length === 2')
                    merged = load_input(root / 'working')[0]['chapters'][0]['elements'][1]
                    self.assertEqual(merged['resolved_md_text'], 'First {manual} paragraph.\nSecond paragraph.')
                    self.assertEqual(merged['pdf_regions'], split_elements[0]['pdf_regions'])
                    self.assertEqual(page.locator('#working [data-element]').count(), 3)
                    self.assertEqual((root / 'accepted/book.json').read_bytes(), accepted_before)
                    prose.click(button='right')
                    self.assertFalse(page.locator('#menu-merge').is_enabled())
                    page.keyboard.press('Escape')
                    page.locator('#accepted [data-element="prose"]').click(button='right')
                    for action in ('menu-bold', 'menu-remove-bold', 'menu-markdown', 'menu-split'):
                        self.assertTrue(page.locator('#' + action).is_enabled())
                    self.assertFalse(page.locator('#menu-merge').is_enabled())
                    self.assertEqual(errors, [])
                    browser.close()
            finally:
                state.stopping.set()
                with state.condition:
                    state.condition.notify_all()
                server.shutdown()
                server.server_close()
                worker.join(timeout=15)
                http.join(timeout=5)
